#!/usr/bin/env node
/**
 * Generate responsive width variants for the hero/section imagery, and record
 * each image's REAL intrinsic size.
 *
 * Why this exists. Every hero shipped as a single full-size file with the
 * markup hard-coding width="1920" height="1080" — and not one image is actually
 * 1920x1080. Seven are portrait (the homepage hero is 1400x2100), so browsers
 * reserved a 16:9 box for a 2:3 image on all ~894 pages, and phones downloaded
 * up to 617KB for a picture sitting behind a 95%-opaque gradient. Mobile LCP
 * measured 4.1s against a 2.5s target.
 *
 * Uses dwebp/cwebp, which ship with macOS via libwebp — no new dependency, and
 * nothing is required at build or deploy time because the variants are
 * committed. Cloudflare just serves static files.
 *
 *   node scripts/build-image-variants.mjs [--force]
 *
 * Writes: public/images/<name>-<width>.webp
 *         src/data/imageMeta.ts   (generated — never hand-edit)
 */
import { readdirSync, statSync, mkdtempSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, basename, extname } from 'node:path';
import { tmpdir } from 'node:os';

const DIR = 'public/images';
const WIDTHS = [480, 768, 1200];
/** Heroes sit under a heavy gradient overlay, so quality can drop a long way
 *  before anything is perceptible. 72 was chosen by eye against the overlay. */
const QUALITY = 72;
const force = process.argv.includes('--force');

const sh = (cmd, args) => execFileSync(cmd, args, { stdio: ['ignore', 'pipe', 'pipe'] });
const kb = (p) => Math.round(statSync(p).size / 1024);

function dimensions(file) {
  const out = sh('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file]).toString();
  const w = /pixelWidth:\s*(\d+)/.exec(out);
  const h = /pixelHeight:\s*(\d+)/.exec(out);
  return w && h ? { w: +w[1], h: +h[1] } : null;
}

const isVariant = (n) => /-\d{3,4}\.webp$/.test(n);
const sources = readdirSync(DIR)
  .filter((n) => n.endsWith('.webp') && !isVariant(n))
  .sort();

const meta = {};
let saved = 0, generated = 0;

for (const name of sources) {
  const src = join(DIR, name);
  const stem = basename(name, extname(name));
  const dim = dimensions(src);
  if (!dim) { console.log(`  ${name}: could not read dimensions — skipped`); continue; }

  const tmp = mkdtempSync(join(tmpdir(), 'imgvar-'));
  const png = join(tmp, 'full.png');
  try {
    sh('dwebp', ['-quiet', src, '-o', png]);

    const variants = [];
    for (const w of WIDTHS) {
      // Never upscale: a 1400px original has no business emitting a 1200 twin
      // that is merely a recompression.
      if (w >= dim.w) continue;
      const out = join(DIR, `${stem}-${w}.webp`);
      if (!existsSync(out) || force) {
        sh('cwebp', ['-quiet', '-resize', String(w), '0', '-q', String(QUALITY), png, '-o', out]);
        generated++;
      }
      variants.push({ w, kb: kb(out) });
    }

    const full = kb(src);
    const smallest = variants.length ? variants[0].kb : full;
    saved += full - smallest;
    meta[name] = { w: dim.w, h: dim.h, variants: variants.map((v) => v.w) };
    const shape = dim.h > dim.w ? 'portrait' : 'landscape';
    console.log(`  ${name.padEnd(26)} ${String(dim.w + 'x' + dim.h).padStart(10)} ${shape.padEnd(10)} ${String(full).padStart(4)}KB -> ${String(smallest).padStart(3)}KB on mobile`);
  } catch (e) {
    console.log(`  ${name}: FAILED — ${String(e.message).split('\n')[0]}`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

const ts = `// GENERATED by scripts/build-image-variants.mjs — do not hand-edit.
//
// Real intrinsic dimensions and the responsive widths available for each image.
// PageHero uses these to emit a correct width/height (so the browser reserves
// the RIGHT box and does not shift) and a srcset (so a phone fetches a phone
// -sized file). Regenerate with: node scripts/build-image-variants.mjs
export interface ImageMeta { w: number; h: number; variants: number[] }

export const imageMeta: Record<string, ImageMeta> = ${JSON.stringify(meta, null, 2)};

/** Intrinsic size for a /images/... src, or null when unknown. */
export function metaFor(src: string): ImageMeta | null {
  const file = src.split('/').pop() || '';
  return imageMeta[file] ?? null;
}

/** srcset for a /images/... src, or '' when no variants exist. */
export function srcsetFor(src: string): string {
  const m = metaFor(src);
  if (!m || !m.variants.length) return '';
  const stem = src.replace(/\\.webp$/, '');
  return [...m.variants.map((w) => \`\${stem}-\${w}.webp \${w}w\`), \`\${src} \${m.w}w\`].join(', ');
}
`;
writeFileSync('src/data/imageMeta.ts', ts);

console.log(`\n  ${sources.length} images, ${generated} variants generated`);
console.log(`  ~${saved}KB less for a phone across the set`);
console.log('  wrote src/data/imageMeta.ts');
